  foreach t in array array['author_social_channels','author_page_sections','author_experiences','author_projects','author_skills','author_education','author_certifications','author_focus_items'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from anon, authenticated', t);
  end loop;
